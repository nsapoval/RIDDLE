"""Instances from **data/l2reg_train_v1/** -- the level-2 training grids.

Two cells, ``l2t25`` (n = 25) and ``l2t50`` (n = 50), 900 replicates each.  Every truth is
**exactly level 2**, regular and tree-child; the ladder is ``l2x{1..3}`` level-2 blobs beside
``l1x{0..3}`` level-1 ones, at ``cu`` in {0.25, 0.5}, giving k = 2-5 at n = 25 and k = 2-7 at
n = 50.  It is the first training data in this repository whose truth is **outside** the level-1
model class ``opc.solve`` builds, which is the whole point of it: every W10 checkpoint before this
was fitted to level-1 truths only.

Nothing here was generated by :mod:`opc.rungrid`, so :func:`opc.rl.instances.build` -- which wants
a ``grid.Cell``, a base-topology pickle and ``N.derive`` -- cannot reach it.  This module is the
:mod:`opc.rl.camus` pattern applied to a second external layout: it says where the files are and
what one row's provenance columns read, and hands the shared half to
:func:`opc.rl.instances.build_from_trees`.

**Measured before anything was built on it** (``scripts/probe_l2reg.py``, and on samples before
that): every network parses under :func:`opc.simulate.networks.from_enewick`, ``level`` is 2 on all
of them, and :func:`~opc.simulate.networks.nontrivial_clusters` of the *regular* form equals the
dataset's own ``<key>.json`` ``regular_network.clusters`` -- an independent oracle that ships
beside the data, compared as **label** sets, never index sets (A103).  ``truth_coverage`` at tau =
2 is median 1.0000 (min 0.9423 over the sampled cells), and the two gene-tree arms are
indistinguishable on it, which is what G-IG1 measured for the inferred arm of our own grids.

**The gene trees are read where they lie.**  Unlike :mod:`opc.rl.camus`, there is no
``prepare_gene_trees`` step and no second copy: the files are already rooted, already free of an
outgroup (the taxon set is exactly the network's labels -- ``OUT`` was grafted and pruned
upstream), already carry branch lengths, and are already one gzipped tree per line, which is
exactly what ``triples.count_newick_file`` and ``extract.count_newick_file`` read.  Copying them
would cost 1.6 GB and create the "two copies, and no rule saying which is authoritative" problem
``scripts/pack_alisim.py`` documents for the AliSim hand-off.

**The inferred arm must read ``<key>.len.nwk.gz`` and not ``<key>.nwk.gz``.**  The dataset ships
both: the bare name is **topology only**, with every ``:length`` stripped.  Fed to W13 that is
A100's failure mode verbatim -- ``blen_*`` collapses to 0, ``bdepth_*`` to 1, ``bsib_*`` to 0 and
``brank_*`` becomes the order the nodes appear in the string -- while ``_tree_stats``' support
cross-check still *passes*, because it counts loci and not lengths.  ``instances._tree_stats``
refuses a length-free locus outright now, so this would fail loudly rather than train silently on
constants; :data:`ARMS` names the right file so it never gets the chance.

**The truth is the regular form.**  ``<key>.regular.enewick`` is what ``<key>.json``'s
``regular_network`` describes and what ``l2reg_eval/check_relaxed.py`` gates against.  On 120
sampled replicates the two forms agree on ``n_retics`` and on the cluster set exactly, and
``spec.k`` equals the regular form's ``n_retics`` on every one -- but only one of them can be the
definition, and it is the one the shipped ground truth is stated over.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path

from opc.rl.instances import Instance, build_from_trees
from opc.simulate import networks as N

__all__ = ["PHASES", "ARMS", "L2Cell", "discover", "truth_of", "spec_of", "build"]

#: ``--phase`` name -> (directory under the dataset root, taxon count).  **Deliberately not in**
#: :data:`opc.grid.PHASES`, for :mod:`opc.rl.camus`' reason: that table means "a phase
#: :mod:`opc.rungrid` can generate", every driver that enumerates a phase resolves through it, and
#: :func:`opc.rl.train.select_split` refuses ``split="all"`` on anything listed there.
PHASES: dict[str, tuple[str, int]] = {"l2t25": ("l2t25", 25), "l2t50": ("l2t50", 50)}

#: arm id -> gene-tree file, relative to the cell directory and formatted with ``key``.  ``""`` is
#: the simulated trees, so its cache directories keep the bare names every landed path uses.
#: ``est_bp1000`` is spelled the same as the AliSim hand-off's arm (:mod:`opc.arms`) because it
#: *is* the same pipeline -- AliSim at 1,000 bp then IQ-TREE -- run by the same code on the far
#: side. The ``.len`` in the filename is load-bearing; see the module docstring.
ARMS: dict[str, str] = {
    "": "trees/{key}.nwk.gz",
    "est_bp1000": "estimated_bp1000/{key}.len.nwk.gz",
}


@dataclass(frozen=True)
class L2Cell:
    """One replicate of one arm.  ``key`` keys the instance cache and every parquet.

    ``key`` is the dataset's own ``n{N}_rep{RRR}_l2x{a}_l1x{b}_cu{c}``.  It is taken verbatim
    rather than re-spelled in this repository's ``n50_rep0_r0_cu0.25_gU0.25-0.5_mid`` grammar for
    two reasons: it already carries ``_rep###`` where :func:`opc.rl.train.split_by_rep` looks, and
    its replicate is **zero-padded to three digits**, so the lexicographic order the six ``*.pkl``
    readers sort by is the numeric one.  ``x75``'s unpadded keys are the counter-example -- there
    ``rep100`` sorts before ``rep80``.
    """

    phase: str
    key: str
    arm: str
    root: Path

    @property
    def n(self) -> int:
        return PHASES[self.phase][1]

    @property
    def cell_dir(self) -> Path:
        return Path(self.root) / PHASES[self.phase][0]

    @property
    def rep(self) -> int:
        return int(self.key.split("_rep")[1].split("_")[0])

    @property
    def base_path(self) -> Path:
        return self.cell_dir / "networks" / f"{self.key}.regular.enewick"

    @property
    def json_path(self) -> Path:
        return self.cell_dir / "networks" / f"{self.key}.json"

    @property
    def trees_path(self) -> Path:
        return self.cell_dir / ARMS[self.arm].format(key=self.key)


def discover(root: Path, phase: str, arm: str = "") -> list[L2Cell]:
    """Every replicate for which the truth, its JSON and this arm's gene trees all exist.

    Enumerated from ``networks/*.json`` rather than from the tree directory, because the JSON is
    the only file that carries the declared split and the shape ladder, and a cell without it could
    not be gated.
    """
    if phase not in PHASES:
        raise KeyError(f"unknown l2reg phase {phase!r}; expected one of {sorted(PHASES)}")
    if arm not in ARMS:
        raise KeyError(f"unknown l2reg arm {arm!r}; expected one of "
                       f"{sorted(a or 'true' for a in ARMS)}")
    root = Path(root)
    base = root / PHASES[phase][0] / "networks"
    if not base.is_dir():
        raise FileNotFoundError(f"{base} does not exist; is --data pointing at l2reg_train_v1?")
    out = []
    for p in sorted(base.glob("*.json")):
        cell = L2Cell(phase, p.stem, arm, root)
        if cell.base_path.exists() and cell.trees_path.exists():
            out.append(cell)
    return out


def spec_of(cell: L2Cell) -> dict:
    """The replicate's shipped metadata -- ``spec``, ``check``, ``blobs``, ``regular_network``."""
    return json.loads(cell.json_path.read_text())


def truth_of(cell: L2Cell) -> N.Network:
    """The replicate's true network, regular form, taxa in the file's own order.

    No outgroup pruning: this dataset's networks carry the ingroup only -- ``OUT`` was grafted for
    sequence simulation and pruned before anything was written down.  :func:`discover`'s callers
    get that checked for free, because :func:`build` hands ``truth.labels`` to the cluster
    extractor and ``clusters_from_newick`` raises on an unknown taxon.
    """
    return N.from_enewick(cell.base_path.read_text())


def build(cell: L2Cell, root: Path, *, m: int = 1000, tau: int = 2) -> Instance:
    """One :class:`~opc.rl.instances.Instance`, by the chain the grid and the other two external
    datasets all use.

    ``root`` is ``results/<phase>/``.  Only the cluster table is written there -- the gene trees
    are read from the dataset in place (see the module docstring) -- and it goes in a per-arm
    directory, because the two arms are different candidate sets over the same truth.
    """
    truth = truth_of(cell)
    spec = spec_of(cell)["spec"]
    suffix = f"_{cell.arm}" if cell.arm else ""
    table = Path(root) / f"clusters_l2reg{suffix}" / f"{cell.key}.parquet"
    return build_from_trees(
        cell.key, truth, cell.trees_path, table, m=m, tau=tau, arm=cell.arm,
        rep=cell.rep, cu=float(spec["cu"]),
        # The blob signature, not the phase: it is what varies within a phase, so it is what makes
        # `rl_instances.py`'s stratum x k table say something.
        stratum=f"l2x{int(spec['n_l2'])}_l1x{int(spec['n_l1'])}",
        source=str(cell.trees_path))

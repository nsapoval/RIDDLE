"""Instances built from **someone else's** simulation -- ``data/N100-2``.

Everything in the study so far was generated by ``opc.simulate``: this generator's networks, this
box's gene trees, this pipeline's cluster tables.  A policy evaluated only on that has been tested
against its own prior.  This module reads an external dataset instead, and it tests three things
that the s50 grid cannot, at once:

1. **A larger ``n``.**  100 ingroup taxa against the 50 the policy was trained on, so 161,700
   triples against 19,600 and a candidate ground set of a different order.
2. **A different prior over networks.**  Reticulation counts run 0-18 where the s50 grid has
   ``k in {1, 2, 4}``, 59 of the 100 replicates are pure *trees*, and the networks are not all
   level-1 -- ``base_net_N100_rs37_3`` is **level-3 and not galled**.  Everything ``opc.solve``
   builds is level-1 by construction, so this is a genuine out-of-class truth.
3. **Gene-tree estimation error.**  The same loci come as true simulated trees and as IQ-TREE
   estimates at two sequence lengths, so the noise the candidate clusters carry is the only
   difference between the arms.

**The outgroup, and why the rooting had to be checked rather than taken.**  Every tree here carries
a grafted ``OUT``.  The *true* gene trees are rooted (root out-degree 2, ``OUT`` a root child in
3,994-3,995 of 4,000).  **The IQ-TREE trees are not**: their root out-degree is **3** on every one
of 4,000 trees, i.e. they are unrooted trifurcations that merely contain ``OUT``.  Reading them as
rooted would take an arbitrary trifurcation as the root and produce clusters that are wrong without
anything raising.  Both arms therefore go through :func:`opc.simulate.outgroup.reroot_on_outgroup`,
which roots on ``OUT``'s pendant edge and deletes it -- one convention for both arms, which is also
what a real analysis would do.  On the ~0.15% of *true* trees where ILS nests ``OUT`` inside the
ingroup, outgroup rooting and the simulator's own root disagree; that is a property of outgroup
rooting, not an error here, and it is identical in both arms.

The truth network's ``OUT`` is pruned too, and that is exact: ``OUT`` is a direct child of a
degree-2 root in all 100 replicates, so pruning is "re-root at the other child".
"""

from __future__ import annotations

import gzip
from dataclasses import dataclass, replace
from pathlib import Path

from opc.rl.instances import Instance, build_from_trees
from opc.simulate import networks as N
from opc.simulate import outgroup as OG

__all__ = ["ExternalCell", "ARMS", "discover", "truth_of", "prepare_gene_trees", "build"]

#: ``arm -> (filename template, whether the trees are rooted as written)``.  The second field is
#: recorded rather than assumed: it is the thing that was wrong on the box.
ARMS = {
    "true": ("gts_{rid}.newick", True),
    "iq_l250": ("iqtree_gts_{rid}.scale0.018000_l250.newick", False),
    "iq_l500": ("iqtree_gts_{rid}.scale0.018000_l500.newick", False),
}

_BASE = "base_net_N100_rs37_{rid}.newick"


@dataclass(frozen=True)
class ExternalCell:
    """One replicate of one arm.  ``key`` keys the instance cache and every parquet."""

    rid: int
    arm: str
    root: Path

    @property
    def key(self) -> str:
        return f"n100_rep{self.rid:03d}_{self.arm}"

    @property
    def base_path(self) -> Path:
        return self.root / _BASE.format(rid=self.rid)

    @property
    def trees_path(self) -> Path:
        return self.root / ARMS[self.arm][0].format(rid=self.rid)

    @property
    def rooted_as_written(self) -> bool:
        return ARMS[self.arm][1]


def discover(root: Path, arm: str = "true") -> list[ExternalCell]:
    """Every replicate for which both the network and this arm's gene trees exist."""
    root = Path(root)
    out = []
    for p in sorted(root.glob("base_net_N100_rs37_*.newick"),
                    key=lambda q: int(q.stem.split("_")[-1])):
        cell = ExternalCell(int(p.stem.split("_")[-1]), arm, root)
        if cell.trees_path.exists():
            out.append(cell)
    return out


def _prune_outgroup(net: N.Network, label: str = OG.OUTGROUP_LABEL) -> N.Network:
    """Drop ``label`` and re-root at the root's other child.

    Exact here rather than in general: ``OUT`` is a direct child of a **degree-2** root in all 100
    replicates (checked), so removing it leaves a single subtree that is already a network.  A
    general leaf-pruning would have to suppress the resulting degree-2 node and could turn a
    reticulation into a parallel edge, which is a different function and is not needed.
    """
    out_v = next((v for v, t in net.leaf_taxon.items() if net.labels[t] == label), None)
    if out_v is None:
        raise ValueError(f"{label!r} is not a leaf of this network")
    if net.tree_parent[out_v] != net.root or len(net.tree_children[net.root]) != 2:
        raise ValueError(f"{label!r} is not a child of a degree-2 root; pruning is not a re-root")
    (new_root,) = [c for c in net.tree_children[net.root] if c != out_v]
    # ``_postorder`` walks from ``net.root``, so ask it from ``new_root`` instead -- that is what
    # says which nodes survive.  ``replace`` rather than ``Network(**net.__dict__)``: the parser
    # attaches ``gammas_in``, which is not a field, and the constructor would refuse it.
    keep = [v for v in N._postorder(replace(net, root=new_root)) if v != out_v]
    idx = {v: i for i, v in enumerate(keep)}
    labels = [net.labels[net.leaf_taxon[v]] for v in keep if v in net.leaf_taxon]
    taxon = {lab: i for i, lab in enumerate(labels)}
    n = len(keep)
    tree_parent = [-1] * n
    tree_children: list[list[int]] = [[] for _ in range(n)]
    leaf_taxon, donor_of, horiz_child = {}, {}, {}
    for v in keep:
        i = idx[v]
        p = net.tree_parent[v]
        if v != new_root and p in idx:
            tree_parent[i] = idx[p]
            tree_children[idx[p]].append(i)
        if v in net.leaf_taxon:
            leaf_taxon[i] = taxon[net.labels[net.leaf_taxon[v]]]
        d = net.donor_of.get(v)
        if d is not None:
            if d not in idx:
                raise ValueError("a hybrid's donor was pruned with the outgroup")
            donor_of[i] = idx[d]
            horiz_child[idx[d]] = i
    t0 = net.time[new_root]
    out = N.Network(
        n_taxa=len(labels), labels=labels, time=[net.time[v] - t0 for v in keep],
        tree_parent=tree_parent, tree_children=tree_children, leaf_taxon=leaf_taxon,
        horiz_child=horiz_child, donor_of=donor_of, retics=[], root=idx[new_root],
        gamma=net.gamma,
        # **Remapped, not copied.**  This function renumbers every node, and ``gammas`` is keyed
        # by node id, so passing it through unchanged would silently attach each hybrid's
        # inheritance probability to a different node -- a wrong answer with nothing raising,
        # which is the failure mode A82 records for the rooting of these same files.
        gammas={idx[h]: g for h, g in getattr(net, "gammas", {}).items() if h in idx})
    out.retics = [N.Reticulation(hybrid=h, donor=d, order=k, time=out.time[h])
                  for k, (h, d) in enumerate(sorted(donor_of.items()))]
    return out


def truth_of(cell: ExternalCell) -> N.Network:
    """The replicate's true network, outgroup pruned, taxa in the file's own order."""
    return _prune_outgroup(N.from_enewick(cell.base_path.read_text()))


def prepare_gene_trees(cell: ExternalCell, dst: Path, taxa, *, max_loci: int = 0) -> dict:
    """Root every tree on ``OUT``, delete it, and write one per line to a gzip at ``dst``.

    Applied to **both** arms.  The IQ-TREE trees are unrooted trifurcations (measured: root
    out-degree 3 on 4,000 of 4,000) and reading them as rooted would silently produce clusters of
    an arbitrary trifurcation; the true trees are rooted already, and for them this is the
    identity on 99.85% of loci and honest outgroup rooting on the rest.

    Every emitted tree is checked to carry exactly ``taxa``.  ``clusters_from_newick`` raises on an
    *unknown* label and is **silent on a missing one**, so a dropped taxon would corrupt the
    cluster table without erroring anywhere -- the trap CLAUDE.md records for ``--keep-ident``.
    """
    expected = frozenset(taxa)
    n_written = n_polytomy = 0
    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    tmp = dst.with_name(dst.name + ".tmp")
    with open(cell.trees_path) as src, gzip.open(tmp, "wt") as fh:
        for line in src:
            line = line.strip()
            if not line:
                continue
            rooted = OG.reroot_on_outgroup(line)
            parent, _len, lab, children = OG.parse_newick(rooted)
            got = frozenset(lab[i] for i in range(len(parent)) if not children[i])
            if got != expected:
                raise ValueError(
                    f"{cell.trees_path.name} locus {n_written}: carries {len(got)} taxa, expected "
                    f"{len(expected)} (missing {sorted(expected - got)[:5]}, "
                    f"extra {sorted(got - expected)[:5]})")
            if len(children[0]) > 2:
                n_polytomy += 1
            fh.write(rooted + "\n")
            n_written += 1
            if max_loci and n_written >= max_loci:
                break
    tmp.replace(dst)
    return {"n_loci": n_written, "n_polytomy": n_polytomy}


def build(cell: ExternalCell, workdir: Path, *, m: int = 1000, tau: int = 2) -> Instance:
    """One :class:`Instance`, by the same chain ``opc.rl.instances.build`` uses.

    The chain is deliberately not re-implemented: gene trees -> ``triples`` for ``obs``, gene trees
    -> ``extract`` for the support table, ``candidates.build`` for the ground set,
    ``true_cluster_rows`` for the target.  Anything else would be a second definition of the
    quantities every gate is stated in.

    **The body is :func:`opc.rl.instances.build_from_trees`**, which is where the chain now lives so
    that this module and :mod:`opc.rl.camus` cannot drift into two definitions of it.  Everything
    above that call is what is specific to *this* dataset: where the files are, and what the row's
    provenance columns read.

    ``finalize(min_support=1)`` -- **not** the module default of 2. A29 measured 51% of ``C`` at
    tau = 0 as having support exactly 1, and the half it would delete is not a uniform half:
    hybrid-signature clusters are over-represented in it by construction.

    **This path does not currently run, and the reason is recorded rather than patched.**
    ``prepare_gene_trees`` below writes length-free Newick, so ``_tree_stats`` raises on
    ``n_degenerate`` (W13), and the landed pickles under ``results/n100ext/`` predate A97's global
    narrowing besides.  Repairing it means deleting ``results/n100ext/genetrees/*.nwk.gz`` and
    re-deriving them with ``keep_lengths=True`` -- a separate piece of work, because
    ``outgroup.reroot_on_outgroup``'s default exists to keep *those* artifacts reproducible.

    **W13's ``bdepth_*`` block reads differently on this dataset and the code cannot tell.**  It
    normalises a node's crown height by the tree's root-to-tip height, which is a coalescent time
    on the simulated grids and, on the estimated arm, a substitution count on trees that are not
    ultrametric (A82: root out-degree 3 on 4,000 of 4,000, rooted here by
    ``prepare_gene_trees``).  The statistic is still scale-free and still well defined -- it is
    "how deep, as a fraction of the deepest tip" -- but it is not the same quantity, and no number
    on this dataset is reported in W13's result.
    """
    truth = truth_of(cell)
    gz = Path(workdir) / f"{cell.key}.nwk.gz"
    if not gz.exists():
        prepare_gene_trees(cell, gz, list(truth.labels), max_loci=m)
    # The path is explicit rather than via ``opc.paths``: a bare ``clusters_`` stem would file
    # into the frozen n = 50 study tier.
    return build_from_trees(
        cell.key, truth, gz, Path(workdir).parent / "clusters_external" / f"{cell.key}.parquet",
        m=m, tau=tau, rep=int(cell.rid), stratum=cell.arm, source=str(cell.trees_path),
        # ``arm=""`` and ``table_arm=cell.arm``: this dataset puts the arm in the *key* and its
        # three arms share one instance directory, so ``Instance.arm`` has always been empty here
        # -- while the landed parquets do carry it.  Both spellings are on disk; keep both.
        arm="", table_arm=cell.arm)

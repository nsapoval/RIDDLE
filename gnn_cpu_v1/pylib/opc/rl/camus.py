"""Instances from **camus-data/** -- a second external dataset, and the first one whose truth is
inside the model class.

Six taxon counts (n15 ... n200) x 50 replicates, each a level-1 species network, 1,000 true gene
trees, 1,000 alignments of 500 bp and (at n15/n25, reps 00-19) IQ-TREE trees estimated from them.
Nothing here was generated by :mod:`opc.rungrid`, so :func:`opc.rl.instances.build` -- which wants
a ``grid.Cell``, a base-topology pickle and ``N.derive`` -- cannot reach it.  The shared half is
:func:`opc.rl.instances.build_from_trees`; this module is only the part that says where the files
are and what one row's provenance columns read.

**Measured before anything was built on it.**  All 300 truth networks parse, and all 300 are
``is_galled`` with ``level == 1`` -- unlike ``data/N100-2``, where 15 of 100 were neither (A82).
``OUT`` is a child of a degree-2 root in all 300, so :func:`opc.rl.external._prune_outgroup` is
exact here for the reason it is exact there, and is imported rather than re-derived.
``truth_coverage`` at tau = 2 is 1.000 on nine of ten pilot cells (0.990 on ``n100/rep00``), and
``n_nonbinary_loci`` is 0 everywhere.

**The two arms are rooted differently, and that is deliberate.**  The true trees are rooted at the
coalescent root and are ultrametric; the IQ-TREE trees are unrooted trifurcations.  So the true arm
goes through :func:`opc.simulate.outgroup.drop_outgroup`, which deletes ``OUT`` and keeps the
rooting, and the estimated arms through ``reroot_on_outgroup(keep_lengths=True)``, which is the
only thing available for an unrooted tree.  That asymmetry is **the training distribution's own**:
``results/x25/genetrees_julia/`` is ultrametric to 1e-8 and ``genetrees_est_julia_bp1000/`` is
outgroup-rooted and is not.

It matters because of one W13 block.  ``blen.accumulate_locus`` normalises a node's crown height by
the tree's root-to-tip height, which is the *crown age* on an ultrametric tree and the longest path
from an arbitrary internal node otherwise -- and ``bdepth_*`` is the block the trained head leans on
hardest (zeroing it costs 0.195 held-out F1 at n = 25).  Here ``OUT`` is a simulated lineage rather
than a grafted one, so deep coalescence nests it inside the ingroup on 24-71% of true loci;
measured on ``n25/rep00``, outgroup rooting leaves **295 of 1,000** loci ultrametric where
:func:`drop_outgroup` leaves **1,000 of 1,000**.

**The candidate set barely cares, which is what makes ``cam_trueog`` a near-clean control -- but it
is not invariant, and the difference is measured rather than waved at.**  Over ten cam25 cells:
``|C_tau2|`` moves by at most 5 clusters, the two ground *sets* share 94.7-100% of their rows
(median 99.3%), support differs on 0-11.5% of the shared rows by at most 20 loci in 1,000, and
``truth_coverage`` is 1.000 either way -- so the *ceiling* is unmoved.  Downstream it is usually
invisible: ``f1_greedy`` is bit-identical on 9 of 10 and differs by one cluster (0.0417) on the
tenth.  Close enough that the arm prices the rooting rather than a different problem, **not** close
enough that one baseline covers both lines -- a report must carry ``f1_greedy`` on each.

**Three of 300 truth networks carry a size-2 cycle and our own eNewick writer cannot round-trip
them** (A11/A39: a shortcut reticulation adds displayed triples and leaves the clustering system
alone, so this generator's output has never contained one).  ``networks.to_enewick`` writes the
subtree at both ``#H1`` occurrences and ``from_enewick`` refuses it -- while PhyloNet *accepts* the
string, which is worse.  They are ``n15/09``, ``n15/15`` and ``n150/04``; the other 200 cells at
n25/n50/n100/n200 are clean.  :func:`shortcut_retics` counts them so a report can NaN ``luay`` on
such a cell rather than quote a distance to a network nobody wrote down.
"""


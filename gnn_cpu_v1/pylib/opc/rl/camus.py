@dataclass(frozen=True)
class CamusCell:
    """One replicate of one arm.  ``key`` keys the instance cache and every parquet."""

    phase: str
    rep: int
    arm: str
    root: Path

    @property
    def n(self) -> int:
        return PHASES[self.phase][1]

    @property
    def key(self) -> str:
        # **No arm in the key.**  ``instances.cache_dir(..., arm)`` gives each arm its own
        # directory; ``opc.rl.external`` predates that and folds the arm into the key instead,
        # which its own docstring says not to generalise.  Two digits, so the lexicographic order
        # six readers take ``test[:max_cells]`` from is the numeric one.
        return f"n{self.n}_rep{self.rep:02d}"

    @property
    def cell_dir(self) -> Path:
        return Path(self.root) / PHASES[self.phase][0] / f"{self.rep:02d}"

    @property
    def base_path(self) -> Path:
        return self.cell_dir / "true_net.nwk"

    @property
    def trees_path(self) -> Path:
        return self.cell_dir / ARMS[self.arm][0]

    @property
    def rooting(self) -> str:
        return ARMS[self.arm][1]


def discover(root: Path, phase: str, arm: str = "") -> list[CamusCell]:
    """Every replicate for which both the network and this arm's gene trees exist.

    The estimated arm is present for 20 of 50 replicates at two phases only, so "exists" is a real
    filter here rather than a formality.
    """
    if phase not in PHASES:
        raise KeyError(f"unknown camus phase {phase!r}; expected one of {sorted(PHASES)}")
    if arm not in ARMS:
        raise KeyError(f"unknown camus arm {arm!r}; expected one of {sorted(ARMS)}")
    root = Path(root)
    base = root / PHASES[phase][0]
    out = []
    for d in sorted(p for p in base.iterdir() if p.is_dir() and p.name.isdigit()):
        cell = CamusCell(phase, int(d.name), arm, root)
        if cell.base_path.exists() and cell.trees_path.exists():
            out.append(cell)
    return out


def truth_of(cell: CamusCell) -> N.Network:
    """The replicate's true network, outgroup pruned, taxa in the file's own order."""
    return _prune_outgroup(N.from_enewick(cell.base_path.read_text()))


def shortcut_retics(net: N.Network) -> int:
    """Reticulations whose two parents are the same node -- a size-2 cycle.

    Invisible to clusters (A11) and therefore harmless to every F1 on the row, but
    ``networks.to_enewick`` emits a string ``from_enewick`` refuses, so any *network*-level metric
    on such a cell -- ``luay`` above all -- is reporting on something nobody can read back.
    """
    return sum(1 for r in net.retics if net.tree_parent[r.hybrid] == r.donor)


def prepare_gene_trees(cell: CamusCell, dst: Path, taxa, *, max_loci: int = 0,
                       partial: int = 0) -> dict:
    """Delete ``OUT`` from every tree and write one per line to a gzip at ``dst``.

    Rooted-and-kept for the true arm, outgroup-rooted for the estimated ones -- see the module
    docstring for why that asymmetry is the right one rather than an inconsistency.

    Three checks, all of them for failures that are otherwise silent:

    * the emitted leaf set is *exactly* ``taxa``.  ``clusters_from_newick`` raises on an **unknown**
      label and is silent on a **missing** one, so a dropped taxon would corrupt the cluster table
      without erroring anywhere -- the trap CLAUDE.md records for IQ-TREE's ``--keep-ident``.
    * no tree comes back without branch lengths.  That is A100's whole failure mode: W13's four
      tree-derived blocks degenerate to constants and a ``brank_*`` that is the Newick write order,
      while the support cross-check downstream still *passes*, because it counts loci not lengths.
    * ``n_ultrametric`` is counted rather than asserted.  It is the statistic that tells the two
      rooting conventions apart (1,000/1,000 vs 295/1,000 on ``n25/rep00``) and it belongs in the
      gate's output, not in a comment.

    ``partial`` (local addition, 2026-10-21, for ``taxmiss_eval``): accept a tree whose leaf set is
    a *subset* of ``taxa`` holding at least ``partial`` taxa, instead of exactly ``taxa``.  The first
    check becomes "no unknown taxon, ``OUT`` present before rooting, and at least ``partial`` left",
    and a tree that fails it still raises -- nothing is skipped, so ``n_loci`` stays the file's own
    count.  The extractor's half of the contract is ``extract.count_newick_file(...,
    drop_partial_root=True)``: a partial tree's root cluster is its taxon sampling.  The return value
    gains ``n_partial``, ``min_taxa`` and ``mean_missing`` (taxa absent per tree, averaged).  Off by
    default, and every landed cell takes the unchanged path.

    ``as_is`` rooting (local addition, 2026-10-22, the ``trn_`` arms): the trees are already rooted
    and OUT-free, so each line is written through untouched; a ``.gz`` trees file is read as such.
    No earlier arm's file ends in ``.gz``, so every landed cell still opens its file as text.
    """
    expected = frozenset(taxa)
    keep_root = cell.rooting == "keep_root"
    as_is = cell.rooting == "as_is"
    if as_is and partial:
        raise ValueError(f"{cell.trees_path}: partial mode needs OUT to root on; as_is has none")
    opener = gzip.open if cell.trees_path.name.endswith(".gz") else open
    n_written = n_polytomy = n_degenerate = n_ultrametric = 0
    n_partial = sum_missing = 0
    min_taxa = len(expected)
    lo, hi = float("inf"), 0.0
    dst = Path(dst)
    dst.parent.mkdir(parents=True, exist_ok=True)
    tmp = dst.with_name(dst.name + ".tmp")
    with opener(cell.trees_path, "rt") as src, gzip.open(tmp, "wt") as fh:
        for line in src:
            line = line.strip()
            if not line:
                continue
            if partial and not _carries(line, OG.OUTGROUP_LABEL):
                raise ValueError(f"{cell.trees_path.name} locus {n_written}: no "
                                 f"{OG.OUTGROUP_LABEL} to root on (partial mode)")
            rooted = (line if as_is
                      else OG.drop_outgroup(line, keep_lengths=True) if keep_root
                      else OG.reroot_on_outgroup(line, keep_lengths=True))
            parent, elen, lab, children = OG.parse_newick(rooted)
            got = frozenset(lab[i] for i in range(len(parent)) if not children[i])
            if partial:
                if not got <= expected or len(got) < partial:
                    raise ValueError(
                        f"{cell.trees_path.name} locus {n_written}: carries {len(got)} taxa, "
                        f"{len(got - expected)} unknown (e.g. {sorted(got - expected)[:5]}); partial "
                        f"mode needs a subset of the {len(expected)} with at least {partial}")
                n_missing = len(expected) - len(got)
                n_partial += n_missing > 0
                sum_missing += n_missing
                min_taxa = min(min_taxa, len(got))
            elif got != expected:
                raise ValueError(
                    f"{cell.trees_path.name} locus {n_written}: carries {len(got)} taxa, expected "
                    f"{len(expected)} (missing {sorted(expected - got)[:5]}, "
                    f"extra {sorted(got - expected)[:5]})")
            if ":" not in rooted:
                n_degenerate += 1
            else:
                lo, hi = min(lo, min(elen[1:], default=0.0)), max(hi, max(elen[1:], default=0.0))
            if len(children[0]) > 2:
                n_polytomy += 1
            depth = [0.0] * len(parent)
            tips = []
            for i in range(1, len(parent)):
                depth[i] = depth[parent[i]] + elen[i]
                if not children[i]:
                    tips.append(depth[i])
            if tips and max(tips) - min(tips) < 1e-6 * max(max(tips), 1e-12):
                n_ultrametric += 1
            fh.write(rooted + "\n")
            n_written += 1
            if max_loci and n_written >= max_loci:
                break
    if n_degenerate:
        tmp.unlink(missing_ok=True)
        raise ValueError(
            f"{cell.trees_path}: {n_degenerate} of {n_written} trees came back with no branch "
            f"length at all.  W13's blen_*/brank_*/bdepth_*/bsib_* would degenerate silently; "
            f"the rooting helper was called without keep_lengths=True.")
    tmp.replace(dst)
    info = {"n_loci": n_written, "n_polytomy": n_polytomy, "n_degenerate": n_degenerate,
            "n_ultrametric": n_ultrametric, "min_branch": (0.0 if lo == float("inf") else lo),
            "max_branch": hi, "rooting": cell.rooting}
    if partial:
        info.update(partial=int(partial), n_partial=n_partial, min_taxa=min_taxa,
                    mean_missing=(sum_missing / n_written if n_written else 0.0))
    return info


def _carries(newick: str, label: str) -> bool:
    """Whether ``label`` is a leaf of ``newick``, by token: ``OUT`` must not match ``OUT2``."""
    i = newick.find(label)
    while i >= 0:
        j = i + len(label)
        if (i == 0 or newick[i - 1] in "(,") and (j == len(newick) or newick[j] in ":,);"):
            return True
        i = newick.find(label, j)
    return False


def build(cell: CamusCell, root: Path, *, m: int = 1000, tau: int = 2) -> Instance:
    """One :class:`Instance`, by the same chain the grid and ``opc.rl.external`` both use.

    ``root`` is ``results/<phase>/``.  The gene-tree gzip and the cluster-table cache go in
    per-arm directories, so the arms never share one -- ``instances.cache_dir``'s docstring names
    ``n100ext``'s single directory as the exception not to generalise.  The paths are spelled here
    rather than through :func:`opc.arms.arm_dirs`, which addresses ``rungrid``'s caches and is
    right to raise on an arm that has none.
    """
    truth = truth_of(cell)
    suffix = f"_{cell.arm}" if cell.arm else ""
    gz = Path(root) / f"genetrees_camus{suffix}" / f"{cell.key}.nwk.gz"
    if not gz.exists():
        prepare_gene_trees(cell, gz, list(truth.labels), max_loci=m)
    return build_from_trees(
        cell.key, truth, gz, Path(root) / f"clusters_camus{suffix}" / f"{cell.key}.parquet",
        m=m, tau=tau, arm=cell.arm, rep=int(cell.rep), stratum=cell.phase,
        source=str(cell.trees_path))
